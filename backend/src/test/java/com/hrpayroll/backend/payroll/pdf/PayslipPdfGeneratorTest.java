package com.hrpayroll.backend.payroll.pdf;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.io.IOException;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Set;
import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.text.PDFTextStripper;
import org.junit.jupiter.api.Test;

/**
 * Unit tests for {@link PayslipPdfGenerator} -- a pure PDFBox-based renderer with no Spring, JPA,
 * filesystem, clock, or HTTP dependency. Loads generated bytes back with PDFBox's {@link Loader}
 * and extracts text with {@link PDFTextStripper} to verify content, exactly as the task requires,
 * rather than asserting on internal drawing calls.
 */
class PayslipPdfGeneratorTest {

    private static PayslipPdfData validData() {
        return new PayslipPdfData(
                3,
                2026,
                "EMP001",
                "Jane Doe",
                "Engineering",
                "Software Engineer",
                new BigDecimal("5000.00"),
                new BigDecimal("500.00"),
                new BigDecimal("200.00"),
                new BigDecimal("5700.00"),
                new BigDecimal("627.00"),
                new BigDecimal("28.50"),
                new BigDecimal("11.40"),
                new BigDecimal("285.00"),
                new BigDecimal("951.90"),
                new BigDecimal("4748.10"));
    }

    private static String extractText(byte[] pdfBytes) throws IOException {
        try (PDDocument document = Loader.loadPDF(pdfBytes)) {
            return new PDFTextStripper().getText(document);
        }
    }

    @Test
    void outputBeginsWithAValidPdfSignature() {
        byte[] bytes = new PayslipPdfGenerator().generate(validData());

        String signature = new String(bytes, 0, 5, StandardCharsets.US_ASCII);

        assertThat(signature).isEqualTo("%PDF-");
    }

    @Test
    void outputCanBeParsedByPdfbox() throws IOException {
        byte[] bytes = new PayslipPdfGenerator().generate(validData());

        try (PDDocument document = Loader.loadPDF(bytes)) {
            assertThat(document.getNumberOfPages()).isGreaterThan(0);
        }
    }

    @Test
    void producesExactlyOnePage() throws IOException {
        byte[] bytes = new PayslipPdfGenerator().generate(validData());

        try (PDDocument document = Loader.loadPDF(bytes)) {
            assertThat(document.getNumberOfPages()).isEqualTo(1);
        }
    }

    @Test
    void containsTheHeading() throws IOException {
        String text = extractText(new PayslipPdfGenerator().generate(validData()));

        assertThat(text).contains("HR Payroll System - Demonstration Payslip");
    }

    @Test
    void containsThePayrollPeriodFormattedAsMonthNameAndYear() throws IOException {
        String text = extractText(new PayslipPdfGenerator().generate(validData()));

        assertThat(text).contains("March 2026");
    }

    @Test
    void containsEmployeeAndPayrollPeriodFields() throws IOException {
        String text = extractText(new PayslipPdfGenerator().generate(validData()));

        assertThat(text).contains("EMP001");
        assertThat(text).contains("Jane Doe");
        assertThat(text).contains("Engineering");
        assertThat(text).contains("Software Engineer");
    }

    @Test
    void containsEveryExactFormattedMonetaryAmount() throws IOException {
        String text = extractText(new PayslipPdfGenerator().generate(validData()));

        assertThat(text).contains("RM 5,000.00"); // base pay
        assertThat(text).contains("RM 500.00"); // housing allowance
        assertThat(text).contains("RM 200.00"); // transport allowance
        assertThat(text).contains("RM 5,700.00"); // gross pay
        assertThat(text).contains("RM 627.00"); // EPF
        assertThat(text).contains("RM 28.50"); // SOCSO
        assertThat(text).contains("RM 11.40"); // EIS
        assertThat(text).contains("RM 285.00"); // income tax
        assertThat(text).contains("RM 951.90"); // total deductions
        assertThat(text).contains("RM 4,748.10"); // net pay
    }

    @Test
    void netPayIsVisiblyRepresentedInExtractedText() throws IOException {
        String text = extractText(new PayslipPdfGenerator().generate(validData()));

        assertThat(text).contains("Net Pay");
        assertThat(text).contains("RM 4,748.10");
    }

    @Test
    void containsTheDemonstrationDisclaimer() throws IOException {
        String text = extractText(new PayslipPdfGenerator().generate(validData()));

        assertThat(text.replace("\n", " ").replaceAll("\\s+", " "))
                .contains("Demonstration only - deduction rates are fixed placeholder figures, "
                        + "not real Malaysian statutory rates. Not for actual payroll, tax, or compliance use.");
    }

    @Test
    void neverContainsAnyPlantedSensitiveValue() throws IOException {
        String text = extractText(new PayslipPdfGenerator().generate(validData()));

        Set<String> plantedSensitiveValues = Set.of(
                "770101-01-0001", // IC number
                "1234567890", // bank account number
                "jane.doe@example.com", // login email
                "0.1100", // rate percentage
                "/data/payroll-pdfs", // filesystem path
                "payroll-run-1/payslip-1.pdf"); // raw pdfPath

        for (String plantedValue : plantedSensitiveValues) {
            assertThat(text).doesNotContain(plantedValue);
        }
    }

    @Test
    void anUnsupportedCharacterInEmployeeNameFailsSafelyWithNoPdfboxDetails() {
        // U+65E5 ("day"/"sun") is outside WinAnsiEncoding, which the Standard 14 fonts use --
        // guaranteed unencodable, unlike typographic punctuation that WinAnsi may actually support.
        PayslipPdfData dataWithUnsupportedCharacter = new PayslipPdfData(
                3,
                2026,
                "EMP001",
                "Tanaka 日中",
                "Engineering",
                "Software Engineer",
                new BigDecimal("5000.00"),
                new BigDecimal("500.00"),
                new BigDecimal("200.00"),
                new BigDecimal("5700.00"),
                new BigDecimal("627.00"),
                new BigDecimal("28.50"),
                new BigDecimal("11.40"),
                new BigDecimal("285.00"),
                new BigDecimal("951.90"),
                new BigDecimal("4748.10"));

        assertThatThrownBy(() -> new PayslipPdfGenerator().generate(dataWithUnsupportedCharacter))
                .isInstanceOf(PayslipPdfGenerationException.class)
                .satisfies(ex -> {
                    String message = ex.getMessage();
                    assertThat(message).doesNotContain("PDType1Font");
                    assertThat(message).doesNotContain("org.apache.pdfbox");
                    assertThat(message).doesNotContain("WinAnsiEncoding");
                    assertThat(message).doesNotContainPattern("(?i)exception");
                });
    }

    @Test
    void doesNotSilentlyRemoveOrAlterSupportedEmployeeNames() throws IOException {
        PayslipPdfData dataWithApostrophe = new PayslipPdfData(
                3,
                2026,
                "EMP002",
                "O'Brien-Smith",
                "Engineering",
                "Software Engineer",
                new BigDecimal("5000.00"),
                new BigDecimal("500.00"),
                new BigDecimal("200.00"),
                new BigDecimal("5700.00"),
                new BigDecimal("627.00"),
                new BigDecimal("28.50"),
                new BigDecimal("11.40"),
                new BigDecimal("285.00"),
                new BigDecimal("951.90"),
                new BigDecimal("4748.10"));

        String text = extractText(new PayslipPdfGenerator().generate(dataWithApostrophe));

        assertThat(text).contains("O'Brien-Smith");
    }

    @Test
    void generatingRepeatedlyClosesAllPdfboxResourcesWithoutFailure() {
        PayslipPdfGenerator generator = new PayslipPdfGenerator();

        for (int i = 0; i < 25; i++) {
            assertThat(generator.generate(validData())).isNotEmpty();
        }
    }

    @Test
    void generatingNeverCreatesAFilesystemFile(@org.junit.jupiter.api.io.TempDir Path watchedDir) throws IOException {
        long before = countFiles(watchedDir);

        new PayslipPdfGenerator().generate(validData());

        long after = countFiles(watchedDir);
        assertThat(after).isEqualTo(before);
    }

    private static long countFiles(Path dir) throws IOException {
        try (var stream = Files.list(dir)) {
            return stream.count();
        }
    }

    @Test
    void rejectsNullData() {
        assertThatThrownBy(() -> new PayslipPdfGenerator().generate(null)).isInstanceOf(NullPointerException.class);
    }
}
