-- period_year had no range check before V13; payroll_runs is a monthly
-- record so a sane bound catches obvious input errors (e.g. a 4-digit year
-- typo) without being an arbitrary business-rule restriction.
ALTER TABLE payroll_runs
    ADD CONSTRAINT chk_payroll_runs_period_year_range CHECK (period_year BETWEEN 2000 AND 2100);

-- Every individual demonstration rate must be a valid percentage (0-1), and
-- the four combined must never exceed 100% of gross pay -- otherwise net
-- pay could go negative by rate configuration alone, before any rounding
-- edge case. Rounding-induced negative net pay (rates summing to exactly 1)
-- is a separate, narrower case handled defensively in application code
-- (PayrollCalculator), not by this constraint.
ALTER TABLE payroll_runs
    ADD CONSTRAINT chk_payroll_runs_epf_rate_snapshot_range CHECK (epf_rate_snapshot BETWEEN 0 AND 1),
    ADD CONSTRAINT chk_payroll_runs_socso_rate_snapshot_range CHECK (socso_rate_snapshot BETWEEN 0 AND 1),
    ADD CONSTRAINT chk_payroll_runs_eis_rate_snapshot_range CHECK (eis_rate_snapshot BETWEEN 0 AND 1),
    ADD CONSTRAINT chk_payroll_runs_income_tax_rate_snapshot_range CHECK (income_tax_rate_snapshot BETWEEN 0 AND 1),
    ADD CONSTRAINT chk_payroll_runs_rate_snapshot_sum CHECK (
        epf_rate_snapshot + socso_rate_snapshot + eis_rate_snapshot + income_tax_rate_snapshot <= 1
    );

-- The DEFAULTs are kept permanently (not dropped after backfill), exactly
-- like the existing leave_requests.duration_type / version columns: the
-- table is currently empty, so there is nothing to backfill in practice,
-- but the defaults continue to safely cover any direct fixture/test insert
-- that omits these columns, and every payslip generated by a run always
-- shares that run's single rate snapshot -- rates are not duplicated onto
-- individual payslips.
